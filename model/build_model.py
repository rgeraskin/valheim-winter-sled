"""Generates the sled undercarriage that replaces the cart's wheels.

Everything is built procedurally with explicit UVs laid out for Valheim's own
textures, which the plugin borrows at runtime (nothing from the game ships with
the mod):

  wood  -> DarkWood_mat  (DarkWoodBeams_d: dark grain on the left half, light on the right)
  iron  -> metalwall     (32 px tiling iron used by the iron cage pieces)
  rope  -> cart_rope     (the cart's own rope)
  fur   -> rug_wolf      (centre of the wolf pelt rug)

Coordinates are the sled prefab's local space in Unity terms: x right, y up,
z forward (the shafts point to +z), ground at y = 0. The cart body sits on top
of this after the plugin lowers it by BODY_DROP. The OBJ is written the way
Unity's own importer expects (x mirrored, counter-clockwise faces), so the
plugin mirrors it back when it loads it.

Usage: python3 model/build_model.py [out.obj]   (stdlib only)
"""

import math
import sys
from pathlib import Path

BODY_DROP = 0.10          # how far the plugin lowers the cart body (keep in sync with SledBuilder.cs)
RUNNER_X = 0.70           # runner centre line, just outside the shafts (x = 0.57..0.64)
SHOE = 0.012              # iron shoe thickness under the runner
RUNNER_H = 0.09           # runner height (perpendicular to its path)
RUNNER_W = 0.07
FLAT_FRONT = 1.04         # where the runner starts to curl up (body front face is at z = 0.98..1.03)
FLAT_BACK = -1.00
STANCHIONS_Z = (-0.80, 0.02, 0.78)   # under the body's side beams (z = -0.89..0.83)
BODY_BOTTOM = 0.418 - BODY_DROP      # lowest point of the lowered cart body
DECK_TOP = 0.582 - BODY_DROP         # top of the (uneven) deck planks
BACK_RAIL_TOP = 0.79 - BODY_DROP     # top of the back wall
BACK_RAIL_Z = (-1.031, -0.946)       # back wall outer/inner faces


def v_add(a, b): return (a[0] + b[0], a[1] + b[1], a[2] + b[2])
def v_sub(a, b): return (a[0] - b[0], a[1] - b[1], a[2] - b[2])
def v_mul(a, s): return (a[0] * s, a[1] * s, a[2] * s)
def v_dot(a, b): return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
def v_cross(a, b): return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])
def v_len(a): return math.sqrt(v_dot(a, a))
def v_norm(a):
    length = v_len(a)
    return (a[0] / length, a[1] / length, a[2] / length) if length > 1e-9 else (0.0, 1.0, 0.0)
def v_lerp(a, b, t): return v_add(a, v_mul(v_sub(b, a), t))


class Mesh:
    def __init__(self):
        self.verts = []      # (pos, normal, uv)
        self.faces = {}      # material -> [(i, j, k)]

    def vert(self, p, n, uv):
        self.verts.append((p, v_norm(n), uv))
        return len(self.verts) - 1

    def tri(self, mat, a, b, c):
        self.faces.setdefault(mat, []).append((a, b, c))

    def quad(self, mat, a, b, c, d):
        """a-b-c-d clockwise when seen from the front, as Unity wants it."""
        self.tri(mat, a, b, c)
        self.tri(mat, a, c, d)

    def check_winding(self):
        """Unity's front faces wind clockwise, i.e. cross(b - a, c - a) points along the normal."""
        flipped = 0
        for tris in self.faces.values():
            for a, b, c in tris:
                pa, pb, pc = (self.verts[i][0] for i in (a, b, c))
                n = v_cross(v_sub(pb, pa), v_sub(pc, pa))
                if v_len(n) > 1e-10 and v_dot(n, self.verts[a][1]) < 0:
                    flipped += 1
        return flipped

    def strip(self, mat, rows):
        """rows: list of vertex index lists, each row the same length; quads between consecutive rows."""
        for r0, r1 in zip(rows, rows[1:]):
            for k in range(len(r0) - 1):
                self.quad(mat, r0[k], r1[k], r1[k + 1], r0[k + 1])

    def write_obj(self, path):
        lines = ["# Winter sled undercarriage, generated by model/build_model.py"]
        for p, _, _ in self.verts:
            lines.append(f"v {-p[0]:.5f} {p[1]:.5f} {p[2]:.5f}")
        for _, _, uv in self.verts:
            lines.append(f"vt {uv[0]:.5f} {uv[1]:.5f}")
        for _, n, _ in self.verts:
            lines.append(f"vn {-n[0]:.5f} {n[1]:.5f} {n[2]:.5f}")
        for mat, tris in self.faces.items():
            lines.append(f"g {mat}")
            lines.append(f"usemtl {mat}")
            for a, b, c in tris:
                # mirroring x flips handedness, so the winding flips too
                lines.append("f " + " ".join(f"{i + 1}/{i + 1}/{i + 1}" for i in (a, c, b)))
        Path(path).write_text("\n".join(lines) + "\n")


def sweep_box(mesh, mat, frames, uv_cols, v_scale, caps=True):
    """Sweeps a rectangle along frames [(pos, tangent, up, side, half_w, half_h, s)].

    Each of the four faces gets its own vertices so the edges stay sharp while
    the faces stay smooth along the path. uv_cols gives the texture u range per
    face (top, outer, bottom, inner); v runs along the path.
    """
    faces = [(+1, 0), (0, +1), (-1, 0), (0, -1)]   # (up sign, side sign) of each face normal
    for (su, ss), (u0, u1) in zip(faces, uv_cols):
        rows = []
        for pos, _, up, side, hw, hh, s in frames:
            n = v_add(v_mul(up, su), v_mul(side, ss))
            # the face's two edges: along the other axis
            if su:
                a = v_add(pos, v_add(v_mul(up, su * hh), v_mul(side, -hw * su)))
                b = v_add(pos, v_add(v_mul(up, su * hh), v_mul(side, hw * su)))
            else:
                a = v_add(pos, v_add(v_mul(side, ss * hw), v_mul(up, hh * ss)))
                b = v_add(pos, v_add(v_mul(side, ss * hw), v_mul(up, -hh * ss)))
            rows.append([mesh.vert(a, n, (u0, s * v_scale)), mesh.vert(b, n, (u1, s * v_scale))])
        mesh.strip(mat, rows)
    if not caps:
        return
    for idx, sign in ((0, -1), (len(frames) - 1, 1)):
        pos, tan, up, side, hw, hh, _ = frames[idx]
        n = v_mul(tan, sign)
        corners = [v_add(pos, v_add(v_mul(side, sx * hw), v_mul(up, sy * hh))) for sx, sy in ((-1, -1), (1, -1), (1, 1), (-1, 1))]
        uvs = [(uv_cols[0][0], 0), (uv_cols[0][1], 0), (uv_cols[0][1], 0.08), (uv_cols[0][0], 0.08)]
        ids = [mesh.vert(c, n, uv) for c, uv in zip(corners, uvs)]
        if sign > 0:
            mesh.quad(mat, *ids)
        else:
            mesh.quad(mat, ids[0], ids[3], ids[2], ids[1])


def box(mesh, mat, center, size, uv_cols, v_scale, taper=1.0, axis="y"):
    """An axis-aligned box swept along `axis`; taper scales the far end's section."""
    ax = {"x": (1, 0, 0), "y": (0, 1, 0), "z": (0, 0, 1)}[axis]
    up = {"x": (0, 1, 0), "y": (0, 0, 1), "z": (0, 1, 0)}[axis]
    side = v_cross(up, ax)
    half_len = v_dot(size, ax) / 2
    hw = abs(v_dot(size, side)) / 2
    hh = v_dot(size, up) / 2
    p0 = v_sub(center, v_mul(ax, half_len))
    p1 = v_add(center, v_mul(ax, half_len))
    frames = [(p0, ax, up, side, hw, hh, 0.0), (p1, ax, up, side, hw * taper, hh * taper, half_len * 2)]
    sweep_box(mesh, mat, frames, uv_cols, v_scale)


def runner_path():
    """Centre line of a runner in (z, y), from the back tip to the curled front tip."""
    y0 = SHOE + RUNNER_H / 2
    pts = []
    # back: a short upturn so the sled can be pushed backwards
    r_back = 0.25
    for i in range(6):
        a = math.radians(-130 + 40 * i / 5)
        pts.append((FLAT_BACK + r_back * math.cos(a), y0 + r_back + r_back * math.sin(a), 1.0))
    # flat bottom
    n_flat = 9
    for i in range(1, n_flat):
        pts.append((FLAT_BACK + (FLAT_FRONT - FLAT_BACK) * i / n_flat, y0, 1.0))
    # front: a closing spiral, the classic Norse curl
    r0, r1, n_curl = 0.31, 0.13, 22
    for i in range(n_curl + 1):
        t = i / n_curl
        a = math.radians(-90 + 172 * t)
        r = r0 - (r0 - r1) * t ** 1.3
        thick = 1.0 - 0.38 * t
        pts.append((FLAT_FRONT + r * math.cos(a), y0 + r0 + r * math.sin(a), thick))
    return pts


def path_frames(x, pts, half_w, half_h, under=0.0, widen=0.0):
    """Frames along a runner path. With `under` > 0 the frames describe a strip of that
    thickness glued to the runner's underside (the iron shoe) instead of the runner itself."""
    frames = []
    s = 0.0
    prev = None
    for i, (z, y, thick) in enumerate(pts):
        nxt = pts[min(i + 1, len(pts) - 1)]
        prv = pts[max(i - 1, 0)]
        tan = v_norm((0.0, nxt[1] - prv[1], nxt[0] - prv[0]))
        up = (0.0, tan[2], -tan[1])
        side = (1.0, 0.0, 0.0)
        pos = (x, y, z)
        if prev is not None:
            s += v_len(v_sub(pos, prev))
        prev = pos
        hh = half_h * thick
        hw = half_w * (0.75 + 0.25 * thick) + widen
        if under > 0:
            pos = v_sub(pos, v_mul(up, hh + under / 2))
            hh = under / 2
        frames.append((pos, tan, up, side, hw, hh, s))
    return frames


def rope_ring(mesh, center, axis, half_a, half_b, a_dir, b_dir, radius=0.011, segs=20, sides=6):
    """A lashing: a rope tube looped around a rectangular section (half sizes a/b along a_dir/b_dir)."""
    pad = radius * 1.4
    ring = []
    total = 0.0
    prev = None
    for i in range(segs + 1):
        t = 2 * math.pi * i / segs
        # superellipse hugs a rectangle with rounded corners
        ca, sa = math.cos(t), math.sin(t)
        pa = math.copysign(abs(ca) ** 0.35, ca) * (half_a + pad)
        pb = math.copysign(abs(sa) ** 0.35, sa) * (half_b + pad)
        p = v_add(center, v_add(v_mul(a_dir, pa), v_mul(b_dir, pb)))
        if prev is not None:
            total += v_len(v_sub(p, prev))
        prev = p
        ring.append((p, total))
    rows = []
    for i, (p, s) in enumerate(ring):
        nxt = ring[(i + 1) % segs][0] if i < segs else ring[1][0]
        prv = ring[i - 1][0] if i > 0 else ring[segs - 1][0]
        tan = v_norm(v_sub(nxt, prv))
        out = v_norm(v_cross(axis, tan))
        row = []
        for k in range(sides + 1):
            ang = 2 * math.pi * k / sides
            n = v_add(v_mul(out, math.cos(ang)), v_mul(axis, math.sin(ang)))
            row.append(mesh.vert(v_add(p, v_mul(n, radius)), n, (s / 0.12, k / sides)))
        rows.append(row)
    mesh.strip("rope", [list(reversed(r)) for r in rows])


def pelt(mesh):
    """A wolf pelt laid on the deck where the rider sits, thrown over the back wall as a backrest.

    The whole rug_wolf texture goes on one sheet: its alpha cut-out (the rug
    shader is alpha-tested) gives the pelt its legs and ragged outline."""
    inner, outer = BACK_RAIL_Z[1], BACK_RAIL_Z[0]
    # the deck planks are uneven; this keeps the pelt above all of them
    lift = 0.05
    # profile in (z, y), from the front edge on the deck, up the inside of the back wall, over, and down outside
    prof = [
        (-0.08, DECK_TOP + lift),
        (-0.45, DECK_TOP + lift + 0.006),
        (-0.70, DECK_TOP + lift),
        (inner + 0.05, DECK_TOP + lift + 0.01),
        (inner + 0.012, DECK_TOP + 0.08),
        (inner + 0.012, BACK_RAIL_TOP - 0.06),
        ((inner + outer) / 2, BACK_RAIL_TOP + lift + 0.004),
        (outer - 0.014, BACK_RAIL_TOP - 0.05),
        (outer - 0.03, BACK_RAIL_TOP - 0.16),
        (outer - 0.05, BACK_RAIL_TOP - 0.30),
    ]
    # densify
    pts = []
    for (z0, y0), (z1, y1) in zip(prof, prof[1:]):
        steps = max(1, int(math.hypot(z1 - z0, y1 - y0) / 0.06))
        for i in range(steps):
            t = i / steps
            pts.append((z0 + (z1 - z0) * t, y0 + (y1 - y0) * t))
    pts.append(prof[-1])
    lengths = [0.0]
    for (z0, y0), (z1, y1) in zip(pts, pts[1:]):
        lengths.append(lengths[-1] + math.hypot(z1 - z0, y1 - y0))
    total = lengths[-1]
    cols = 10
    half_w = 0.56
    for face in (1, -1):
        rows = []
        for i, ((z, y), s) in enumerate(zip(pts, lengths)):
            nxt = pts[min(i + 1, len(pts) - 1)]
            prv = pts[max(i - 1, 0)]
            tz, ty = nxt[0] - prv[0], nxt[1] - prv[1]
            tl = math.hypot(tz, ty) or 1.0
            # normal pointing away from the wood (up on the deck, into the bed on the wall)
            nz, ny = -ty / tl, tz / tl
            row = []
            edge_t = s / total
            for k in range(cols + 1):
                u = k / cols
                x = (u - 0.5) * 2 * half_w
                # the hide sags a little between the legs where it hangs free
                sag = -0.015 * math.sin(math.pi * u) if edge_t > 0.85 else 0.0
                p = (x, y + ny * 0.004 * face + sag, z + nz * 0.004 * face)
                n = (0.0, ny * face, nz * face)
                # head end at the front of the sled, hind legs hanging over the back
                uv = (u, 1.0 - edge_t)
                row.append(mesh.vert(p, n, uv))
            rows.append(row)
        if face > 0:
            mesh.strip("fur", rows)
        else:
            mesh.strip("fur", [list(reversed(r)) for r in rows])


def build():
    mesh = Mesh()
    pts = runner_path()
    # u ranges on DarkWoodBeams_d: dark grain on 0..0.5, light grain on 0.5..1
    dark = [(0.04, 0.20), (0.22, 0.40), (0.06, 0.22), (0.26, 0.44)]
    light = [(0.56, 0.72), (0.74, 0.92), (0.58, 0.74), (0.78, 0.94)]
    for x in (-RUNNER_X, RUNNER_X):
        frames = path_frames(x, pts, RUNNER_W / 2, RUNNER_H / 2)
        sweep_box(mesh, "wood", frames, dark, v_scale=0.8)
        # iron shoe along the bottom and up the front of the curl
        shoe_pts = [p for p in pts if not (p[0] > FLAT_FRONT + 0.02 and p[1] > 0.30)]
        shoe = path_frames(x, shoe_pts, RUNNER_W / 2, RUNNER_H / 2, under=SHOE, widen=0.004)
        sweep_box(mesh, "iron", shoe, [(0, 0.5), (0, 0.5), (0, 0.5), (0, 0.5)], v_scale=2.0)
        for z in STANCHIONS_Z:
            top = BODY_BOTTOM + 0.03
            bottom = SHOE + RUNNER_H - 0.01
            box(mesh, "wood", (x, (top + bottom) / 2, z), (0.075, top - bottom, 0.075), dark, v_scale=0.8, taper=0.85)
            for dz in (-0.058, 0.058):
                rope_ring(mesh, (x, SHOE + RUNNER_H / 2, z + dz), (0, 0, 1), RUNNER_W / 2, RUNNER_H / 2, (1, 0, 0), (0, 1, 0))
    for z in STANCHIONS_Z:
        y = SHOE + RUNNER_H + 0.11
        box(mesh, "wood", (0.0, y, z), (2 * RUNNER_X + 0.10, 0.055, 0.06), light, v_scale=0.6, axis="x")
        for x in (-RUNNER_X, RUNNER_X):
            inward = x - math.copysign(0.07, x)   # beside the stanchion, not through it
            rope_ring(mesh, (inward, y, z), (1, 0, 0), 0.030, 0.0275, (0, 0, 1), (0, 1, 0), segs=16)
    # a lashing near each curl tip
    tip = len(pts) - 6
    for x in (-RUNNER_X, RUNNER_X):
        z, y, thick = pts[tip]
        frames = path_frames(x, pts, RUNNER_W / 2, RUNNER_H / 2)
        pos, tan, up, side, hw, hh, _ = frames[tip]
        rope_ring(mesh, pos, tan, hw, hh, side, up, radius=0.009, segs=16)
    pelt(mesh)
    return mesh


def main():
    out = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "WinterSled" / "Resources" / "sled_undercarriage.obj")
    mesh = build()
    tris = sum(len(t) for t in mesh.faces.values())
    flipped = mesh.check_winding()
    if flipped:
        sys.exit(f"{flipped} of {tris} triangles face the wrong way")
    mesh.write_obj(out)
    print(f"{out}: {len(mesh.verts)} verts, {tris} tris, materials {sorted(mesh.faces)}")


if __name__ == "__main__":
    main()
